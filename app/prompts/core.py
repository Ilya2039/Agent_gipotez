def build_filter_goals_prompt(raw_text: str) -> str:
    """Попросить LLM отфильтровать реальные цели/намерения из свободного ответа пользователя.

    Требования:
    - Игнорировать и не возвращать: пустые ответы, «пропустить», «skip», «хз», «не знаю», «да/нет», смайлы,
      любые короткие междометия и нерелевантные фразы.
    - Вернуть JSON‑массив строк; каждая строка — одна цель/намерение (≤ 140 символов).
    - Не более 8 пунктов. Если нет валидных целей — верни []
    """
    return (
        "РОЛЬ: Ассистент-аналитик.") + (
        " ОТФИЛЬТРУЙ реальные цели/намерения из ответа пользователя;" 
        " игнорируй пустые/служебные ответы типа 'пропустить', 'skip', 'хз', 'не знаю', 'да', 'нет', смайлы и прочее." 
        " Верни только JSON-массив строк (≤8), каждая строка ≤ 140 символов. Если целей нет — верни [].\n"
        f"Ответ пользователя: {raw_text}\nJSON:"
    )

