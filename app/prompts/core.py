from __future__ import annotations
from typing import List, Optional

"""
🎯 Unified prompt builders for the strategy bot.
Фокус: реалистичные, но содержательные и инсайтные гипотезы + прикладные вопросы.
"""

def build_generate_discovery_question_prompt(
    qa_json: str,
    dialog_json: str = "",
    examples_text: str = "",
    avoid: Optional[List[str]] = None,
    count: int = 1,
    theme: str = "",
    avoid_unknown: Optional[List[str]] = None,
) -> str:
    context_block = (
        f"\nКонтекст (материалы клиента + протоколы встреч, укорочено, JSON):\n{dialog_json}\n"
        if dialog_json else ""
    )
    theme_block = f"\nТема анализа (если указана, фокусируйся на ней): {theme}\n" if theme else ""
    examples_block = (
        "\nПримеры типовых гипотез (для ориентира; НЕ выбирай их, формулируй свои вопросы):\n"
        + examples_text + "\n" if examples_text else ""
    )
    avoid_block = (
        ("\nНе повторяй и не перефразируй эти вопросы:\n- " + "\n- ".join(avoid)) if avoid else ""
    )
    unknown_block = (
        ("\nСмени тему и не уточняй эти аспекты — КМ ответил, что не знает:\n- " + "\n- ".join(avoid_unknown))
        if avoid_unknown else ""
    )
    return (
        "РОЛЬ: Старший интервьюер/консультант по стратегии.\n"
        + "ЦЕЛЬ: уточнить бизнес-модель клиента, выявить ключевые проблемы и возможные точки роста.\n"
        + "ОПИРАЙСЯ: на факты из материалов и протоколов встреч, ищи слабые сигналы и недосказанности.\n"
        + "ТРЕБОВАНИЯ: вопрос прикладной, конкретный, ≤ 18 слов, заканчивается на '?'. Без общих фраз.\n"
        + "СТРОГИЙ ВЫВОД — только JSON-массив из ровно N вопросов.\n"
        + f"N={count}.\n"
        + f"История Q/A (JSON):\n{qa_json}\n"
        + f"{context_block}{theme_block}{examples_block}{avoid_block}{unknown_block}"
        + "Формат ответа: [\"Вопрос?\"]"
    )


def build_decide_next_action_prompt(
    theme: str,
    qa_json: str,
    dialog_json: str = "",
    prefer_non_finance: bool = True,
) -> str:
    context_block = (
        f"\nКонтекст (материалы клиента + протоколы встреч, укорочено, JSON):\n{dialog_json}\n"
        if dialog_json else ""
    )
    deprior = (
        "Финансовые гипотезы предлагай только при явных фактах о долгах, убытках или прибыли.\n"
        if prefer_non_finance else ""
    )
    return (
        "РОЛЬ: Старший стратег-консультант с отраслевой экспертизой.\n"
        + "ЦЕЛЬ: определить следующий шаг — уточнить, запросить данные, выдвинуть гипотезу или завершить.\n"
        + "ФОКУС: реальные управленческие вызовы, рыночные факторы и контекст отрасли.\n"
        + deprior
        + "КРИТЕРИИ:\n"
        + "- Если получено < 3 осмысленных ответов и нет очень сильных сигналов из материалов/протоколов → обязательно action=ask.\n"
        + "- Не хватает цифр → action=request_file.\n"
        + "- Есть устойчивая картина И гипотеза выглядит нетривиальной (не пересказывает текст, оригинальность ≥ 9/10) → action=hypothesis.\n"
        + "- Противоречия между ответами и протоколами → уточняющий вопрос.\n"
        + "Требования к вопросу (если ask): прикладной, ≤ 18 слов, без общих фраз, со знаком '?'.\n"
        + "СТРОГИЙ JSON-ВЫВОД:\n"
        + '{"action":"ask|request_file|hypothesis|stop","question":"<если action=ask>","note":"<кратко почему>"}\n'
        + f"Тема: {theme}\nИстория Q/A (JSON):\n{qa_json}\n{context_block}JSON:"
    )


def build_generate_free_hypothesis_prompt(
    theme: str,
    qa_json: str,
    dialog_json: str = "",
    examples_text: str = "",
    prefer_non_finance: bool = True,
) -> str:
    context_block = (
        f"\nКонтекст (материалы клиента + протоколы встреч, укорочено, JSON):\n{dialog_json}\n"
        if dialog_json else ""
    )
    examples_block = (
        "\nПримеры типовых гипотез (для ориентира; не копируй и не перефразируй — ищи неожиданные рычаги и ортогональные идеи):\n"
        + examples_text + "\n"
        if examples_text else ""
    )
    deprior = (
        "\nФинансовые гипотезы допускаются только при прямых сигналах о долгах, убытках или прибыли.\n"
        if prefer_non_finance else ""
    )
    return (
        "РОЛЬ: Ведущий стратег-консультант с системным и креативным мышлением.\n"
        + "ЦЕЛЬ: выдвинуть одну стратегическую гипотезу — свежую, управляемую, с добавленной ценностью для бизнеса.\n"
        + "ПОДХОД (креатив в рамках корпоративных ограничений):\n"
        + "- Не повторяй формулировки из файлов/ответов — предложи неожиданный рычаг.\n"
        + "- Комбинируй слабые сигналы, отраслевые тренды, поведение конкурентов и факты из протоколов.\n"
        + "- Используй кросс‑отраслевые аналогии и контрфактуальные сценарии ('а что если ...') без фантазий.\n"
        + "- Один доминирующий рычаг: продукт/пакетирование, бизнес‑модель/цены, партнёрство/экосистема, GTM/каналы, операции/автоматизация, орг‑дизайн/роли, данные/ML. Горизонт 6–18 мес.\n"
        + "- Внутри reason обязательно: 25–40 слов; 'почему сейчас' и 1 ранний индикатор успеха.\n"
        + "- Границы: соблюдай риск/комплаенс и бренд‑безопасность, не предлагай сомнительные практики или нереалистичные CAPEX.\n"
        + deprior
        + "СТРОГИЙ ВЫВОД — только JSON:\n"
        + "{\n"
        + '  "hypothesis": "<чёткая, стратегически осмысленная формулировка>",\n'
        + '  "reason": "<25–40 слов: 1) ключевые сигналы из Q/A и материалов; 2) почему сейчас; 3) риск/ограничение; 4) ранний индикатор (1 шт.); 5) ожидаемый эффект/метрика и горизонт>",\n'
        + '  "tags": ["отрасль", "подотрасль", "ключевые процессы или факторы"]\n'
        + "}\n"
        + "КРИТЕРИИ: новизна (≥8/10), реализуемость, управленческий смысл, инсайт; соответствие риск/комплаенс.\n"
        + "ИНСАЙТ 10/10: добавь неожиданный рычаг (например: партнёрство, платформенность, новая бизнес‑модель, смена роли в цепочке) — либо иной столь же ортогональный ход.\n"
        + "ЗАПРЕТ: общие формулы ('повысить эффективность/оптимизировать процессы/улучшить маркетинг'), пустые лозунги и копипаст из файлов.\n"
        + f"Тема: {theme}\nИстория (Q/A JSON):\n{qa_json}\n{context_block}{examples_block}JSON:"
    )


def build_generate_alternative_hypothesis_prompt(
    qa_json: str,
    dialog_json: str = "",
    examples_text: str = "",
    avoid_hypothesis: str = "",
    prefer_non_finance: bool = True,
) -> str:
    context_block = (
        f"\nКонтекст (материалы клиента + протоколы встреч, укорочено, JSON):\n{dialog_json}\n"
        if dialog_json else ""
    )
